    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed

        String marca = inputMarca.getText();
        String modelo = inputModelo.getText();
        String patente = inputPatente.getText();
        Number valorAsientos = (Number) cmbAsientos.getSelectedItem();
        int asientos = (valorAsientos != null) ? valorAsientos.intValue() : 0;
        Cliente cliente = (Cliente) cmbClientes.getSelectedItem();

        if (cmbClientes.getSelectedIndex() < 0
                || cmbAsientos.getSelectedIndex() < 0
                || "".equals(marca)
                || "".equals(modelo)) {
            listaServ.mostrarMensaje("Debe completar todos los campos antes de confirmar",
                    "Datos incompletos", "error");
            return;
        }
        if (Auto.esPatenteValida(patente)) {
            autoAEditar.setCapacidad(asientos);
            autoAEditar.setCliente(cliente);
            autoAEditar.setDominio(patente);
            autoAEditar.setMarca(marca);
            autoAEditar.setModelo(modelo);

            try {
                controladoraLogica.editarAuto(autoAEditar);
                listaServ.mostrarMensaje("Vehículo editado con éxito", "Éxito", "info");
                this.dispose();
            } catch (Exception e) {
                listaServ.mostrarMensaje("Patente inválida o repetida",
                        "Patente inválida", "error");
            }

        }

    }//GEN-LAST:event_btnConfirmarActionPerformed

