    private void precargarDatosAutoSeleccionado(){
        inputPatente.setText(autoAEditar.getDominio());
        inputModelo.setText(autoAEditar.getModelo());
        inputMarca.setText(autoAEditar.getMarca());
        cmbClientes.setSelectedItem(autoAEditar.getCliente());
        cmbAsientos.setSelectedItem(autoAEditar.getCapacidad());
    }
    
    private void cargarClientes() {
        ArrayList<Cliente> listaClientes = controladoraLogica.traerListaClientes();
        for (Cliente cli : listaClientes) {
            cmbClientes.addItem(cli);
        }
    }
