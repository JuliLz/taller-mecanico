    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        String nombre = inputNombre.getText();
        String descripcion = inputDescripcion.getText();
        
        if(nombre.equals("") || descripcion.equals("")) {
            listaServMec.mostrarMensaje("Complete todos los datos antes de confirmar",
                    "Error", "error");
            return;
        }
        tipoServicioAEditar.setNombre(nombre);
        tipoServicioAEditar.setDescripcion(descripcion);
        controladoraLogica.editarTipoServicio(tipoServicioAEditar);
        listaServMec.mostrarMensaje("Tipo de servicio modificado con éxito", "Éxito", "info");
        this.dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

