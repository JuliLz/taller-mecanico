    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int cantidadFilas = tableTipoServicio.getRowCount();
        if (cantidadFilas == 0) {
            mostrarMensaje("No hay ningún tipo de servicio para eliminar", "Error", "error");
            this.dispose();
            return;
        }
        int filaSeleccionada = tableTipoServicio.getSelectedRow();
        if (filaSeleccionada == -1) {
            mostrarMensaje("No hay ningún tipo de servicio seleccionado", "Error", "error");
            return;
        }
        int idTipoServicioSeleccionado = (int) tableTipoServicio.getValueAt(filaSeleccionada, 0);
        controladoraLogica.eliminarTipoServicio(idTipoServicioSeleccionado);
        mostrarMensaje("Tipo de Servicio borrado con éxito", "Éxito", "info");
        cargarTabla();
    }//GEN-LAST:event_btnEliminarActionPerformed

