    private void cargarTabla() {
        DefaultTableModel tabla = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        String[] columnas = {"ID", "Nombre", "Descripcion"};
        tabla.setColumnIdentifiers(columnas);
        ArrayList<TipoServicio> listaTipoServicio = controladoraLogica.traerListaTiposServicios();
                
        if (listaTipoServicio != null) {
            for (TipoServicio tipoServ : listaTipoServicio) {
                Object[] fila = {
                    tipoServ.getId(),
                    tipoServ.getNombre(),
                    tipoServ.getDescripcion(),
                };
                tabla.addRow(fila);
            }
        }
        tableTipoServicio.setModel(tabla);
    }

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int cantidadFilas = tableTipoServicio.getRowCount();
        if (cantidadFilas == 0) {
            mostrarMensaje("No hay ningun tipo de servicio para editar", "Error", "error");
            return;
        }
        int filaSeleccionada = tableTipoServicio.getSelectedRow();
        if (filaSeleccionada == -1) {
            mostrarMensaje("No hay ningun tipo de servicio seleccionado", "Error", "error");
            return;
        }
        int idTipoServicioSeleccionado = (int) tableTipoServicio.getValueAt(filaSeleccionada, 0);
        TipoServicio tipoServicioSeleccionado = controladoraLogica.consultarTipoServicio(idTipoServicioSeleccionado);

        EditarTipoServicio ventanaEditarTipoServicio = new EditarTipoServicio(tipoServicioSeleccionado);
        ventanaEditarTipoServicio.setVisible(true);
        ventanaEditarTipoServicio.setLocationRelativeTo(null);
        this.dispose();

    }//GEN-LAST:event_btnEditarActionPerformed

    public void mostrarMensaje(String mensaje, String titulo, String tipoMensaje) {
        if (tipoMensaje.equals("info")) {
            JOptionPane.showMessageDialog(this,
                    mensaje,
                    titulo,
                    JOptionPane.INFORMATION_MESSAGE);
        }
        if (tipoMensaje.equals("error")) {
            JOptionPane.showMessageDialog(this,
                    mensaje,
                    titulo,
                    JOptionPane.WARNING_MESSAGE);
        }

    }

