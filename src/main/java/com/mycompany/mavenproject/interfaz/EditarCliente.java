    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        String nombre = inputNombre.getText();
        String apellido = inputApellido.getText();
        long documento = (long) inputDocumento.getValue();
        long telefono = (long) inputTelefono.getValue();
        
        if(nombre.equals("") || apellido.equals("") || documento <= 0 || telefono <= 0) {
            listaServMec.mostrarMensaje("Complete todos los datos antes de confirmar",
                    "Error", "error");
            return;
        }
        clienteAEditar.setNombre(nombre);
        clienteAEditar.setApellido(apellido);
        clienteAEditar.setTelefono(telefono);
        clienteAEditar.setDocumento(documento);
        controladoraLogica.editarCliente(clienteAEditar);
        listaServMec.mostrarMensaje("Cliente modificado con éxito", "Éxito", "info");
        this.dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

