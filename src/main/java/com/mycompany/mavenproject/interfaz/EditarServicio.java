    private void precargarDatosServicioSeleccionado(){
        if (servicioAEditar == null) {
            return;
        }
        cmbMecanico.setSelectedItem(servicioAEditar.getMecanico());
        spinnerFechaInicio.setValue(servicioAEditar.getFechaInicio());
        if (servicioAEditar.getFechaFin() != null) {
            spinnerFechaFin.setValue(servicioAEditar.getFechaFin());
        }
        cmbVehiculo.setSelectedItem(servicioAEditar.getAuto());
        cmbTipoServicio.setSelectedItem(servicioAEditar.getTipoServicio());
        inputDescripcion.setText(servicioAEditar.getDescripcion() == null
                ? "" : servicioAEditar.getDescripcion());
        inputImporte.setValue(servicioAEditar.getImporte());
        checkFinalizado.setSelected(servicioAEditar.isFinalizado());
    }
    
    
    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        Number valorImporte = (Number) inputImporte.getValue();
        double importe = (valorImporte != null) ? valorImporte.doubleValue() : 0;
        
        servicioAEditar.setMecanico((Mecanico) cmbMecanico.getSelectedItem());
        servicioAEditar.setFechaInicio((Date) spinnerFechaInicio.getValue());
        servicioAEditar.setFechaFin((Date) spinnerFechaFin.getValue());
        servicioAEditar.setAuto((Auto) cmbVehiculo.getSelectedItem());
        servicioAEditar.setTipoServicio((TipoServicio) cmbTipoServicio.getSelectedItem());
        servicioAEditar.setDescripcion(inputDescripcion.getText());
        if(importe <= 0) {
            listaServicios.mostrarMensaje("Ingrese un importe válido", "Error", "error");
            return;
        }
        servicioAEditar.setImporte(importe);
        servicioAEditar.setFinalizado(checkFinalizado.isSelected());
        controladoraLogica.editarServicioMecanico(servicioAEditar);
        
        listaServicios.mostrarMensaje("Servicio editado con éxito", "Éxito", "info");
        
        this.dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

