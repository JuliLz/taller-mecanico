    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        Mecanico mecanico = (Mecanico) cmbMecanico.getSelectedItem();
        Auto vehiculo = (Auto) cmbVehiculo.getSelectedItem();
        TipoServicio tipoServicio = (TipoServicio) cmbTipoServicio.getSelectedItem();
        String descripcion = inputDescripcion.getText();
        Number valorImporte = (Number) inputImporte.getValue();
        int importe = (valorImporte != null) ? valorImporte.intValue() : 0;

        if (cmbMecanico.getSelectedIndex() < 0
                || cmbVehiculo.getSelectedIndex() < 0
                || cmbTipoServicio.getSelectedIndex() < 0
                || "".equals(descripcion)
                || importe <= 0) {
            listaServ.mostrarMensaje("Debe completar todos los campos antes de confirmar",
                    "Datos incompletos", "error");
        } else {
            listaServ.mostrarMensaje("Servicio cargado con éxito", "Éxito", "info");
            controladoraLogica.darDeAltaServicioMecanico(importe, mecanico, vehiculo, descripcion, tipoServicio);
            this.dispose();
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

