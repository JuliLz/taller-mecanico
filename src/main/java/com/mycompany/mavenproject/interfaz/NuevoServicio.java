    private void cargarListaMecanicos() {
        ArrayList<Mecanico> listaMecanicos = controladoraLogica.traerListaMecanicos();
        for (Mecanico mec : listaMecanicos) {
            cmbMecanico.addItem(mec);
        }
        cmbMecanico.setSelectedIndex(-1);
    }

    private void cargarListaAutos() {
        ArrayList<Auto> listaAutos = controladoraLogica.traerListaAutos();

        for (Auto auto : listaAutos) {
            cmbVehiculo.addItem(auto);
        }
        cmbVehiculo.setSelectedIndex(-1);
    }

    private void cargarListaTipoServicio() {
        ArrayList<TipoServicio> listaTipoServ = controladoraLogica.traerListaTiposServicios();

        for (TipoServicio tipoServ : listaTipoServ) {
            cmbTipoServicio.addItem(tipoServ);
        }
        cmbTipoServicio.setSelectedIndex(-1);
    }
