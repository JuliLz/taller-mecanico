    private void cargarTabla() {
        DefaultTableModel tabla = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        String[] columnas = {"ID", "Capacidad", "Dominio", "Marca", "Modelo", "Cliente"};
        tabla.setColumnIdentifiers(columnas);
        ArrayList<Auto> listaAutos = controladoraLogica.traerListaAutos();
                
        if (listaAutos != null) {
            for (Auto auto : listaAutos) {
                Object[] fila = {
                    auto.getId(),
                    auto.getCapacidad(),
                    auto.getDominio(),
                    auto.getMarca(),
                    auto.getModelo(),
                    auto.getCliente().getNombre() + " " + auto.getCliente().getApellido()
                };
                tabla.addRow(fila);
            }
        }
        tableVehiculos.setModel(tabla);
    }

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int cantidadFilas = tableVehiculos.getRowCount();
        if (cantidadFilas == 0) {
            mostrarMensaje("No hay ningun vehiculo para editar", "Error", "error");
            return;
        }
        int filaSeleccionada = tableVehiculos.getSelectedRow();
        if (filaSeleccionada == -1) {
            mostrarMensaje("No hay vehiculo seleccionado", "Error", "error");
            return;
        }
        int idAutoSeleccionado = (int) tableVehiculos.getValueAt(filaSeleccionada, 0);
        Auto autoSeleccionado = controladoraLogica.consultarAuto(idAutoSeleccionado);

        EditarVehiculo ventanaEditarVehiculo = new EditarVehiculo(autoSeleccionado);
        ventanaEditarVehiculo.setVisible(true);
        ventanaEditarVehiculo.setLocationRelativeTo(null);
        this.dispose();

    }//GEN-LAST:event_btnEditarActionPerformed

    public void mostrarMensaje(String mensaje, String titulo, String tipoMensaje) {
        if (tipoMensaje.equals("info")) {
            JOptionPane.showMessageDialog(this,
                    mensaje,
                    titulo,
                    JOptionPane.INFORMATION_MESSAGE);
        }
        if (tipoMensaje.equals("error")) {
            JOptionPane.showMessageDialog(this,
                    mensaje,
                    titulo,
                    JOptionPane.WARNING_MESSAGE);
        }

    }
    


