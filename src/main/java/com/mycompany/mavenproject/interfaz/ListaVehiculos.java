    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int cantidadFilas = tableVehiculos.getRowCount();
        if (cantidadFilas == 0) {
            mostrarMensaje("No hay ningún vehículo para eliminar", "Error", "error");
            this.dispose();
            return;
        }
        int filaSeleccionada = tableVehiculos.getSelectedRow();
        if (filaSeleccionada == -1) {
            mostrarMensaje("No hay ningún vehículo seleccionado", "Error", "error");
            return;
        }
        int idAutoSeleccionado = (int) tableVehiculos.getValueAt(filaSeleccionada, 0);
        controladoraLogica.eliminarAuto(idAutoSeleccionado);
        mostrarMensaje("vehículo borrado con éxito", "Éxito", "info");
        cargarTabla();
    }//GEN-LAST:event_btnEliminarActionPerformed

