    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        Cliente clienteNuevo = new Cliente();
        String nombre = inputNombre.getText();
        String apellido = inputApellido.getText();

        Number valorDocumento = (Number) inputDocumento.getValue();
        long documento = (valorDocumento != null) ? valorDocumento.longValue() : 0;

        Number valorTelefono = (Number) inputTelefono.getValue();
        long telefono = (valorTelefono != null) ? valorTelefono.longValue() : 0;

        if (nombre.equals("") || apellido.equals("") || documento <= 0 || telefono <= 0) {
            listaServMec.mostrarMensaje("Complete todos los datos antes de confirmar",
                    "Error", "error");
            return;
        }

        clienteNuevo.setNombre(nombre);
        clienteNuevo.setApellido(apellido);
        clienteNuevo.setDocumento(documento);
        clienteNuevo.setTelefono(telefono);
        controladoraLogica.crearCliente(clienteNuevo);
        listaServMec.mostrarMensaje("Cliente registrado con éxito", "Éxito", "info");
        this.dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

