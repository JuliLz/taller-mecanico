    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        String nombre = inputNombre.getText();
        String apellido = inputApellido.getText();
        
        if(nombre.equals("") || apellido.equals("")) {
            listaServMec.mostrarMensaje("Complete todos los datos antes de confirmar",
                    "Error", "error");
            return;
        }
        mecanicoAEditar.setNombre(nombre);
        mecanicoAEditar.setApellido(apellido);
        controladoraLogica.editarMecanico(mecanicoAEditar);
        listaServMec.mostrarMensaje("Mecánico modificado con éxito", "Éxito", "info");
        this.dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

