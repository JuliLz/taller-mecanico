    private void cargarTabla() {
        DefaultTableModel tabla = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        String[] columnas = {"ID", "Dominio", "Fecha Inicio", "Fecha Fin", "Importe", "Mecanico", "Marca", "Modelo", "Descripcion", "Tipo de servicio", "Finalizado"};
        tabla.setColumnIdentifiers(columnas);
        ArrayList<ServicioMecanico> listaServicios = controladoraLogica.traerListaServiciosMecanicos();
        
        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
        
        if (listaServicios != null) {
            for (ServicioMecanico servMec : listaServicios) {
                Object[] fila = {
                    servMec.getId(),
                    servMec.getAuto() == null ? "Sin vehículo" : servMec.getAuto().getDominio(),
                    formatearFecha(servMec.getFechaInicio()),
                    formatearFechaFin(servMec.getFechaFin(), formato),
                    "$" + servMec.getImporte(),
                    servMec.getMecanico() == null ? "Sin mecánico" : servMec.getMecanico(),
                    servMec.getAuto() == null ? "" : servMec.getAuto().getMarca(),
                    servMec.getAuto() == null ? "" : servMec.getAuto().getModelo(),
                    servMec.getDescripcion(),
                    servMec.getTipoServicio(),
                    servMec.isFinalizado() ? "Si" : "No"
                };
                tabla.addRow(fila);
            }
        }
        tableServiciosMecanicos.setModel(tabla);
    }

    private String formatearFecha(java.util.Date fecha) {
        return fecha == null ? "Sin fecha" : new SimpleDateFormat("dd/MM/yyyy").format(fecha);
    }

    private String formatearFechaFin(java.util.Date fecha, SimpleDateFormat formato) {
        if (fecha == null || formato.format(fecha).equals("01/02/1900")) {
            return "Sin fecha de fin";
        }
        return formato.format(fecha);
    }

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int cantidadFilas = tableServiciosMecanicos.getRowCount();
        if (cantidadFilas == 0) {
            mostrarMensaje("No hay ningun servicio para editar", "Error", "error");
            return;
        }
        int filaSeleccionada = tableServiciosMecanicos.getSelectedRow();
        if (filaSeleccionada == -1) {
            mostrarMensaje("No hay ningun servicio seleccionado", "Error", "error");
            return;
        }
        int idservicioSeleccionado = (int) tableServiciosMecanicos.getValueAt(filaSeleccionada, 0);
        ServicioMecanico servicioSeleccionado = controladoraLogica.consultarServicioMecanico(idservicioSeleccionado);

        EditarServicio ventanaEditarServicio = new EditarServicio(servicioSeleccionado);
        ventanaEditarServicio.setVisible(true);
        ventanaEditarServicio.setLocationRelativeTo(null);
        this.dispose();

    }//GEN-LAST:event_btnEditarActionPerformed

    public void mostrarMensaje(String mensaje, String titulo, String tipoMensaje) {
        if (tipoMensaje.equals("info")) {
            JOptionPane.showMessageDialog(this,
                    mensaje,
                    titulo,
                    JOptionPane.INFORMATION_MESSAGE);
        }
        if (tipoMensaje.equals("error")) {
            JOptionPane.showMessageDialog(this,
                    mensaje,
                    titulo,
                    JOptionPane.WARNING_MESSAGE);
        }

    }

