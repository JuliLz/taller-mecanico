    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int cantidadFilas = tableServiciosMecanicos.getRowCount();
        if (cantidadFilas == 0) {
            mostrarMensaje("No hay ningún servicio para eliminar", "Error", "error");
            this.dispose();
            return;
        }
        int filaSeleccionada = tableServiciosMecanicos.getSelectedRow();
        if (filaSeleccionada == -1) {
            mostrarMensaje("No hay ningún servicio seleccionado", "Error", "error");
            return;
        }
        int idServicioSeleccionado = (int) tableServiciosMecanicos.getValueAt(filaSeleccionada, 0);
        controladoraLogica.eliminarServicioMecanico(idServicioSeleccionado);
        mostrarMensaje("Servicio borrado con éxito", "Éxito", "info");
        cargarTabla();
    }//GEN-LAST:event_btnEliminarActionPerformed

